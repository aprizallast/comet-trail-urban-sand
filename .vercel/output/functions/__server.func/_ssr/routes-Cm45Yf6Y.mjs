function formatUsd(n) {
	if (n == null || isNaN(n) || n === 0) return "$0.00";
	if (n >= 1e6) return "$" + (n / 1e6).toFixed(2) + "M";
	if (n >= 1e3) return "$" + (n / 1e3).toFixed(1) + "K";
	if (n >= 1) return "$" + n.toFixed(2);
	if (n >= .01) return "$" + n.toFixed(4);
	if (n >= 1e-4) return "$" + n.toFixed(6);
	if (n >= 1e-8) return "$" + n.toFixed(8);
	return "$" + n.toExponential(3);
}
function formatPct(n) {
	if (n == null || isNaN(n)) return "0.00%";
	return (n > 0 ? "+" : "") + n.toFixed(2) + "%";
}
function truncateAddr(addr) {
	if (!addr) return "";
	return addr.slice(0, 6) + "..." + addr.slice(-4);
}
async function copyToClipboard(text) {
	if (!text) return false;
	try {
		await navigator.clipboard.writeText(text);
		return true;
	} catch {
		const area = document.createElement("textarea");
		area.value = text;
		area.style.position = "fixed";
		area.style.opacity = "0";
		document.body.appendChild(area);
		area.select();
		const success = document.execCommand("copy");
		area.remove();
		return success;
	}
}
function playAlertChime(volume = .15) {
	try {
		const AudioCtx = window.AudioContext || window.webkitAudioContext;
		if (!AudioCtx) return;
		const ctx = new AudioCtx();
		const osc = ctx.createOscillator();
		const gain = ctx.createGain();
		osc.type = "sine";
		osc.frequency.setValueAtTime(587.33, ctx.currentTime);
		osc.frequency.exponentialRampToValueAtTime(880, ctx.currentTime + .12);
		const vol = Math.max(.01, Math.min(volume, 1));
		gain.gain.setValueAtTime(vol, ctx.currentTime);
		gain.gain.exponentialRampToValueAtTime(.001, ctx.currentTime + .35);
		osc.connect(gain);
		gain.connect(ctx.destination);
		osc.start();
		osc.stop(ctx.currentTime + .35);
	} catch {}
}
