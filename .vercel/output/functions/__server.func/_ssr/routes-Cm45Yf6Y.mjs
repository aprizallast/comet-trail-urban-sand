/**
* Safe JSON parser helper to prevent "Unexpected token '<', <!doctype... is not valid JSON"
*/
async function safeFetchJson(url, options, timeoutMs = 8e3) {
	try {
		const controller = new AbortController();
		const timer = setTimeout(() => controller.abort(), timeoutMs);
		const res = await fetch(url, {
			...options,
			signal: controller.signal
		});
		clearTimeout(timer);
		if (!res.ok) return null;
		const text = await res.text();
		if (!text || text.trim().startsWith("<") || text.trim().startsWith("<!doctype") || text.trim().startsWith("<!DOCTYPE")) return null;
		return JSON.parse(text);
	} catch {
		return null;
	}
}
